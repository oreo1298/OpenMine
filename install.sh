#!/usr/bin/env bash
# OpenMine installer for Linux (works on Arch, Debian, Ubuntu, Fedora, openSUSE, ...).
#
# Install or update (same command for both):
#   ./install.sh                  for your user only, into ~/.local (no root needed)
#   ./install.sh --system         for all users, into /usr/local (asks for sudo)
#
# Without cloning the repository:
#   curl -fsSL https://raw.githubusercontent.com/oreo1298/OpenMine/main/install.sh | bash
#
# Uninstall:
#   ./install.sh --uninstall      (add --system if you installed with --system)
#
# Run ./install.sh --help for all options.

set -euo pipefail
umask 022

REPO="oreo1298/OpenMine"
APP_ID="io.github.oreo1298.OpenMine"
MIN_QT="6.5"
PYSIDE_REQ="PySide6-Essentials>=${MIN_QT}"
MARKER="# OpenMine launcher (generated by install.sh)"

ORIG_ARGS=("$@")
action="install"
scope="user"
prefix=""
qt="auto"
ref=""
purge=0
assume_yes=0

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
note() { printf '    %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
die() { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

usage() {
    cat <<EOF
Usage: install.sh [options]

Installs OpenMine, or updates an existing installation in place.

Where to install:
  --user            Install for the current user in ~/.local (default)
  --system          Install for all users in /usr/local (uses sudo)
  --prefix DIR      Install into DIR instead (DIR/bin, DIR/share, DIR/lib)

Qt (PySide6) source:
  --system-qt       Require the PySide6 package from your distribution
  --venv            Always download PySide6 from PyPI into a private
                    environment, even if your distribution provides it
                    (default: use the distribution's PySide6 >= ${MIN_QT} when
                    installed, otherwise download it)

What to install:
  --ref REF         Git branch, tag or commit to download when the script is
                    not run from a checkout (default: latest release, or main)

Removing:
  --uninstall       Remove OpenMine (use the same --user/--system/--prefix
                    you installed with)
  --purge           With --uninstall: also delete your settings and
                    statistics (~/.config/openmine)
  -y, --yes         Don't ask for confirmation

  -h, --help        Show this help
EOF
}

while [ $# -gt 0 ]; do
    case "$1" in
        --user) scope="user" ;;
        --system) scope="system" ;;
        --prefix)
            [ $# -ge 2 ] || die "--prefix needs a directory"
            prefix="$2"; scope="custom"; shift ;;
        --prefix=*) prefix="${1#*=}"; scope="custom" ;;
        --system-qt) qt="system" ;;
        --venv) qt="venv" ;;
        --ref)
            [ $# -ge 2 ] || die "--ref needs a value"
            ref="$2"; shift ;;
        --ref=*) ref="${1#*=}" ;;
        --uninstall) action="uninstall" ;;
        --purge) purge=1 ;;
        -y|--yes) assume_yes=1 ;;
        -h|--help) usage; exit 0 ;;
        *) die "unknown option: $1 (see --help)" ;;
    esac
    shift
done

case "$scope" in
    user) prefix="${HOME:?HOME is not set}/.local" ;;
    system) prefix="/usr/local" ;;
    custom)
        [ -n "$prefix" ] || die "--prefix needs a directory"
        case "$prefix" in /*) ;; *) prefix="$PWD/$prefix" ;; esac ;;
esac
prefix="${prefix%/}"
case "$prefix" in *"'"*) die "the install prefix must not contain a single quote" ;; esac

BINDIR="$prefix/bin"
LIBDIR="$prefix/lib/openmine"
DATADIR="$prefix/share"
APPDIR="$DATADIR/applications"
ICONDIR="$DATADIR/icons/hicolor"
METADIR="$DATADIR/metainfo"
LAUNCHER="$BINDIR/openmine"

# Is root needed to write to $prefix?
needs_root() {
    [ "$(id -u)" -eq 0 ] && return 1
    local dir="$prefix"
    while [ ! -e "$dir" ]; do dir="$(dirname "$dir")"; done
    [ -w "$dir" ] && return 1
    return 0
}

confirm() {
    [ "$assume_yes" -eq 1 ] && return 0
    # Read from the terminal even when the script itself comes from a pipe.
    if [ -r /dev/tty ]; then
        local answer
        printf '%s [y/N] ' "$1" > /dev/tty
        read -r answer < /dev/tty || return 1
        case "$answer" in [yY]*) return 0 ;; *) return 1 ;; esac
    fi
    return 0
}

installed_version() {
    sed -n 's/^__version__ = "\(.*\)"/\1/p' "$LIBDIR/app/openmine/__init__.py" 2>/dev/null || true
}

# ---------------------------------------------------------------- uninstall
do_uninstall() {
    local SUDO=""
    if needs_root; then
        command -v sudo >/dev/null 2>&1 || die "need root permissions to modify $prefix"
        SUDO="sudo"
    fi
    if [ ! -d "$LIBDIR" ] && [ ! -e "$LAUNCHER" ]; then
        warn "OpenMine does not seem to be installed in $prefix"
        if [ "$scope" = "user" ] && [ -d /usr/local/lib/openmine ]; then
            note "There is a system-wide installation; remove it with: $0 --uninstall --system"
        fi
    else
        local version
        version="$(installed_version)"
        confirm "Remove OpenMine ${version:-} from $prefix?" || die "cancelled"
        say "Removing OpenMine ${version:-} from $prefix"
        if [ -e "$LAUNCHER" ]; then
            if grep -qF "$MARKER" "$LAUNCHER" 2>/dev/null; then
                $SUDO rm -f "$LAUNCHER"
            else
                warn "not removing $LAUNCHER: it was not created by this installer"
            fi
        fi
        $SUDO rm -rf "$LIBDIR"
        $SUDO rm -f "$APPDIR/$APP_ID.desktop" "$METADIR/$APP_ID.metainfo.xml"
        $SUDO rm -f "$ICONDIR/scalable/apps/$APP_ID.svg"
        local size
        for size in 16 24 32 48 64 128 256 512; do
            $SUDO rm -f "$ICONDIR/${size}x${size}/apps/$APP_ID.png"
        done
        refresh_desktop_caches "$SUDO"
    fi
    if [ "$purge" -eq 1 ]; then
        local config="${XDG_CONFIG_HOME:-$HOME/.config}/openmine"
        if [ -d "$config" ]; then
            say "Deleting settings and statistics in $config"
            rm -rf "$config"
        fi
    else
        note "Your settings and statistics are kept in ${XDG_CONFIG_HOME:-~/.config}/openmine"
        note "(run with --uninstall --purge to delete them as well)."
    fi
    say "Done."
}

refresh_desktop_caches() {
    local SUDO="${1:-}"
    if command -v update-desktop-database >/dev/null 2>&1 && [ -d "$APPDIR" ]; then
        $SUDO update-desktop-database -q "$APPDIR" 2>/dev/null || true
    fi
    if [ -d "$ICONDIR" ]; then
        if [ -f "$ICONDIR/icon-theme.cache" ] && command -v gtk-update-icon-cache >/dev/null 2>&1; then
            $SUDO gtk-update-icon-cache -q -t -f "$ICONDIR" 2>/dev/null || true
        else
            $SUDO touch "$ICONDIR" 2>/dev/null || true
        fi
    fi
}

if [ "$action" = "uninstall" ]; then
    do_uninstall
    exit 0
fi

# ------------------------------------------------------------------ sources
SCRIPT_DIR=""
if [ -n "${BASH_SOURCE[0]:-}" ] && [ -f "${BASH_SOURCE[0]}" ]; then
    SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
fi

TMP=""
cleanup() { if [ -n "$TMP" ]; then rm -rf "$TMP"; fi; }
trap cleanup EXIT

fetch() {  # fetch URL [OUTPUT]
    if command -v curl >/dev/null 2>&1; then
        if [ $# -ge 2 ]; then curl -fsSL "$1" -o "$2"; else curl -fsSL "$1"; fi
    elif command -v wget >/dev/null 2>&1; then
        if [ $# -ge 2 ]; then wget -q "$1" -O "$2"; else wget -q "$1" -O -; fi
    else
        die "need curl or wget to download OpenMine"
    fi
}

if [ -n "$SCRIPT_DIR" ] && [ -f "$SCRIPT_DIR/src/openmine/__init__.py" ] && [ -z "$ref" ]; then
    SRC="$SCRIPT_DIR"
else
    if [ -z "$ref" ]; then
        ref="$(fetch "https://api.github.com/repos/$REPO/releases/latest" 2>/dev/null \
            | sed -n 's/^ *"tag_name": *"\([^"]*\)".*/\1/p' | head -n 1 || true)"
        ref="${ref:-main}"
    fi
    say "Downloading OpenMine ($ref)"
    TMP="$(mktemp -d)"
    fetch "https://github.com/$REPO/archive/$ref.tar.gz" "$TMP/openmine.tar.gz" \
        || die "could not download https://github.com/$REPO/archive/$ref.tar.gz"
    tar -xzf "$TMP/openmine.tar.gz" -C "$TMP"
    SRC="$(find "$TMP" -mindepth 1 -maxdepth 1 -type d | head -n 1)"
    [ -f "$SRC/src/openmine/__init__.py" ] || die "downloaded archive does not look like OpenMine"
fi
NEW_VERSION="$(sed -n 's/^__version__ = "\(.*\)"/\1/p' "$SRC/src/openmine/__init__.py")"

# Writing to /usr/local needs root: run the rest of the script with sudo.
if needs_root; then
    command -v sudo >/dev/null 2>&1 || die "need root permissions to write to $prefix (try --user)"
    say "Root permissions are needed to install into $prefix"
    args=()
    for arg in "${ORIG_ARGS[@]+"${ORIG_ARGS[@]}"}"; do
        case "$arg" in --ref|--ref=*) ;; *) args+=("$arg") ;; esac
    done
    # The sources are already here, so don't download them again.
    sudo env PYTHON="${PYTHON:-}" bash "$SRC/install.sh" "${args[@]+"${args[@]}"}"
    exit $?
fi

# ------------------------------------------------------------------- python
PYTHON="${PYTHON:-}"
if [ -z "$PYTHON" ]; then
    for candidate in python3 python; do
        if command -v "$candidate" >/dev/null 2>&1 \
            && "$candidate" -c 'import sys; sys.exit(sys.version_info < (3, 9))' 2>/dev/null; then
            PYTHON="$(command -v "$candidate")"
            break
        fi
    done
fi
[ -n "$PYTHON" ] || die "Python 3.9 or newer is required. Install it with your package manager
       (Arch: pacman -S python, Debian/Ubuntu: apt install python3, Fedora: dnf install python3)."

has_system_qt() {
    "$PYTHON" - "$MIN_QT" <<'PY' 2>/dev/null
import sys
from PySide6 import QtCore, QtGui, QtWidgets  # noqa: F401
have = tuple(int(x) for x in QtCore.qVersion().split(".")[:2])
need = tuple(int(x) for x in sys.argv[1].split("."))
sys.exit(0 if have >= need else 1)
PY
}

distro_hint() {
    local id=""
    if [ -r /etc/os-release ]; then
        # shellcheck disable=SC1091
        id="$(. /etc/os-release; echo "${ID:-} ${ID_LIKE:-}")"
    fi
    case "$id" in
        *arch*) echo "sudo pacman -S pyside6" ;;
        *fedora*|*rhel*) echo "sudo dnf install python3-pyside6" ;;
        *) echo "" ;;
    esac
}

use_venv=0
case "$qt" in
    system)
        hint="$(distro_hint)"
        has_system_qt || die "PySide6 ${MIN_QT}+ was not found for $PYTHON.
       Install it from your distribution${hint:+ (e.g. $hint)} or run without --system-qt." ;;
    venv) use_venv=1 ;;
    auto) has_system_qt || use_venv=1 ;;
esac

# ------------------------------------------------------------------ install
OLD_VERSION="$(installed_version)"
if [ -n "$OLD_VERSION" ]; then
    say "Updating OpenMine $OLD_VERSION -> $NEW_VERSION in $prefix"
else
    say "Installing OpenMine $NEW_VERSION into $prefix"
fi

mkdir -p "$LIBDIR" "$BINDIR"

if [ "$use_venv" -eq 1 ]; then
    if ! "$PYTHON" -c 'import venv, ensurepip' 2>/dev/null; then
        hint="$(distro_hint)"
        die "Python's venv module is missing, so PySide6 can't be downloaded.
       On Debian/Ubuntu run:  sudo apt install python3-venv
       Or install PySide6 from your distribution instead${hint:+:  $hint}"
    fi
    # (Re)create the environment if it is missing or was made with another Python version.
    want="$("$PYTHON" -c 'import sys; print(sys.version_info[:2])')"
    have="$("$LIBDIR/venv/bin/python" -c 'import sys; print(sys.version_info[:2])' 2>/dev/null || true)"
    if [ "$want" != "$have" ]; then
        say "Creating a private Python environment for Qt (PySide6) in $LIBDIR/venv"
        rm -rf "$LIBDIR/venv"
        "$PYTHON" -m venv "$LIBDIR/venv"
    fi
    say "Downloading/updating PySide6 from PyPI (about 100 MB the first time)"
    "$LIBDIR/venv/bin/python" -m pip install --quiet --disable-pip-version-check --upgrade pip \
        || warn "could not upgrade pip; continuing"
    "$LIBDIR/venv/bin/python" -m pip install --disable-pip-version-check --upgrade --progress-bar on \
        "$PYSIDE_REQ" || die "could not install PySide6 from PyPI (check your internet connection)"
    RUN_PYTHON="$LIBDIR/venv/bin/python"
    QT_SOURCE="PyPI (private environment)"
else
    if [ -d "$LIBDIR/venv" ]; then
        note "Using the system's PySide6 now; removing the old private environment"
        rm -rf "$LIBDIR/venv"
    fi
    RUN_PYTHON="$PYTHON"
    QT_SOURCE="system packages"
fi

# Application code
rm -rf "$LIBDIR/app"
mkdir -p "$LIBDIR/app"
cp -r "$SRC/src/openmine" "$LIBDIR/app/openmine"
find "$LIBDIR/app" -name '__pycache__' -type d -prune -exec rm -rf {} +
cat > "$LIBDIR/app/launch.py" <<'PY'
import sys

from openmine.app import main

sys.exit(main())
PY
"$RUN_PYTHON" -m compileall -q "$LIBDIR/app" >/dev/null 2>&1 || true

# Keep a copy of this script so the installation can remove itself later.
cp "$SRC/install.sh" "$LIBDIR/install.sh"
chmod 755 "$LIBDIR/install.sh"
cat > "$LIBDIR/uninstall.sh" <<EOF
#!/bin/sh
# Removes OpenMine from $prefix. Add --purge to delete settings and statistics too.
exec bash '$LIBDIR/install.sh' --uninstall --prefix '$prefix' "\$@"
EOF
chmod 755 "$LIBDIR/uninstall.sh"

# Launcher
cat > "$LAUNCHER" <<EOF
#!/bin/sh
$MARKER
# Uninstall with: $LIBDIR/uninstall.sh
exec '$RUN_PYTHON' '$LIBDIR/app/launch.py' "\$@"
EOF
chmod 755 "$LAUNCHER"

# Desktop integration
mkdir -p "$APPDIR" "$METADIR" "$ICONDIR/scalable/apps"
exec_line="$LAUNCHER"
case "$exec_line" in *[[:space:]]*) exec_line="\"$exec_line\"" ;; esac
sed "s|^Exec=.*|Exec=$exec_line|" "$SRC/data/$APP_ID.desktop" > "$APPDIR/$APP_ID.desktop"
chmod 644 "$APPDIR/$APP_ID.desktop"
install -m 644 "$SRC/data/$APP_ID.metainfo.xml" "$METADIR/$APP_ID.metainfo.xml"
install -m 644 "$SRC/data/icons/$APP_ID.svg" "$ICONDIR/scalable/apps/$APP_ID.svg"
for png in "$SRC"/src/openmine/assets/"$APP_ID"-*.png; do
    size="${png##*-}"
    size="${size%.png}"
    mkdir -p "$ICONDIR/${size}x${size}/apps"
    install -m 644 "$png" "$ICONDIR/${size}x${size}/apps/$APP_ID.png"
done
refresh_desktop_caches

cat > "$LIBDIR/INSTALL_INFO" <<EOF
version=$NEW_VERSION
installed=$(date '+%Y-%m-%d %H:%M:%S')
prefix=$prefix
python=$RUN_PYTHON
qt=$QT_SOURCE
EOF

# Sanity check: can Python load Qt and the game?
if ! check_output="$("$RUN_PYTHON" -c 'import sys; sys.path.insert(0, sys.argv[1]); import openmine.window' \
        "$LIBDIR/app" 2>&1)"; then
    warn "OpenMine is installed, but Python could not load Qt:"
    printf '%s\n' "$check_output" | tail -n 3 >&2
fi

# Pip's Qt needs a few system libraries for X11 that minimal systems may lack.
if [ "$use_venv" -eq 1 ] && command -v ldd >/dev/null 2>&1; then
    xcb="$("$RUN_PYTHON" -c 'import os, PySide6; print(os.path.join(os.path.dirname(PySide6.__file__), "Qt", "plugins", "platforms", "libqxcb.so"))' 2>/dev/null || true)"
    if [ -n "$xcb" ] && [ -f "$xcb" ]; then
        missing="$(ldd "$xcb" 2>/dev/null | awk '/not found/ {print $1}' | sort -u | tr '\n' ' ')"
        if [ -n "$missing" ]; then
            warn "Qt is missing these system libraries for X11 sessions: $missing"
            if command -v apt-get >/dev/null 2>&1; then
                # Debian package names follow the library names: libfoo.so.1 -> libfoo1
                pkgs="$(tr ' ' '\n' <<< "$missing" | sed -E 's/\.so\.([0-9]+)$/ \1/' \
                    | awk '{ print ($1 ~ /[0-9]$/) ? $1 "-" $2 : $1 $2 }' | tr '\n' ' ')"
                note "Install them with: sudo apt install $pkgs"
            else
                note "Install them with your package manager to run OpenMine on X11."
            fi
            note "(Wayland sessions are not affected.)"
        fi
    fi
fi

say "OpenMine $NEW_VERSION is installed (Qt from $QT_SOURCE)."
note "Start it from your application menu or by running: openmine"
case ":$PATH:" in
    *":$BINDIR:"*) ;;
    *) note "Note: $BINDIR is not in your PATH; run $LAUNCHER directly or add it to PATH." ;;
esac
note "Update:    run this installer again"
note "Uninstall: $LIBDIR/uninstall.sh"
